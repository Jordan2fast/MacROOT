#!/usr/bin/env python3
"""Regenerates MacROOT/Core/MacROOTScript.swift from Scripts/macROOT.sh.

Run this after editing macROOT.sh so the app embeds the current script:
    python3 Scripts/embed_script.py
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "Scripts" / "macROOT.sh").read_text()
if '"""#' in src or "\\#(" in src:
    sys.exit("macROOT.sh contains a sequence that can't be embedded in a Swift raw string.")
if not src.endswith("\n"):
    src += "\n"
version = re.search(r'^VERSION="([^"]+)"', src, re.M).group(1)
out = root / "MacROOT" / "Core" / "MacROOTScript.swift"
out.write_text(
    "// Generated by Scripts/embed_script.py from Scripts/macROOT.sh - do not edit by hand.\n"
    "enum EmbeddedScript {\n"
    f'    static let version = "{version}"\n'
    '    static let text = #"""\n'
    f'{src}"""#\n'
    "}\n"
)
print(f"Embedded macROOT {version} ({len(src)} bytes) -> {out.relative_to(root)}")
